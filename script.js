  function handleNav(nav) {
    const map = {
      dashboard: { category: "semua", label: "Dashboard" },
      all: { category: "semua", label: "Semua Jadwal" },
      guru: { category: "guru", label: "Jadwal Guru" },
      siswa: { category: "siswa", label: "Kelas" },
      prodi: { category: "prodi", label: "Program Keahlian" },
      favorit: { category: "__favorit__", label: "Favorit" },
      pengaturan: { category: state.category, label: "Pengaturan" },
    };
    const target = map[nav];
    if (!target) return;
    els.breadcrumbCurrent.textContent = target.label;
    if (nav === "pengaturan") {
      showToast("Pengaturan lanjutan akan tersedia pada rilis berikutnya.", "success");
      return;
    }
    if (nav === "favorit") {
      renderFavoritesView();
      return;
    }
    // reset chip UI to match nav category
    const chipMap = { semua: "semua", guru: "guru", siswa: "siswa", prodi: "prodi" };
    const chipVal = chipMap[target.category] || "semua";
    Array.from(els.categoryChips.children).forEach((c) => {
      c.classList.toggle("is-active", c.dataset.filter === chipVal);
      c.setAttribute("aria-selected", c.dataset.filter === chipVal ? "true" : "false");
    });
    state.category = chipVal;
    state.page = 1;
    render();
  }

  function resetFilters() {
    state.query = ""; state.category = "semua"; state.jenjang = "semua"; state.sort = "az"; state.page = 1;
    els.searchInput.value = "";
    els.jenjangSelect.value = "semua";
    els.sortSelect.value = "az";
    Array.from(els.categoryChips.children).forEach((c) => {
      c.classList.toggle("is-active", c.dataset.filter === "semua");
      c.setAttribute("aria-selected", c.dataset.filter === "semua" ? "true" : "false");
    });
    render();
  }

  /* ---------------------------------------------------------------------
   * Derived data
   * ------------------------------------------------------------------- */
  function getFiltered(overrideFavoritesOnly) {
    let list = SCHEDULE_DATA.slice();

    if (overrideFavoritesOnly) {
      list = list.filter((it) => state.favorites.has(it.id));
    } else if (state.category !== "semua") {
      list = list.filter((it) => it.category === state.category);
    }

    if (state.jenjang !== "semua") {
      list = list.filter((it) => it.jenjang === state.jenjang);
    }

    if (state.query) {
      const q = state.query;
      list = list.filter((it) =>
        it.title.toLowerCase().includes(q) ||
        it.categoryLabel.toLowerCase().includes(q) ||
        it.jurusan.toLowerCase().includes(q) ||
        it.filename.toLowerCase().includes(q)
      );
    }

    list.sort((a, b) => {
      switch (state.sort) {
        case "za": return b.title.localeCompare(a.title);
        case "terbaru": return b.date.localeCompare(a.date) || a.title.localeCompare(b.title);
        case "terlama": return a.date.localeCompare(b.date) || a.title.localeCompare(b.title);
        case "kategori": return a.categoryLabel.localeCompare(b.categoryLabel) || a.title.localeCompare(b.title);
        default: return a.title.localeCompare(b.title);
      }
    });

    return list;
  }


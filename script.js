  function renderStats() {
    const total = SCHEDULE_DATA.length;
    const guru = SCHEDULE_DATA.filter((i) => i.category === "guru").length;
    const siswa = SCHEDULE_DATA.filter((i) => i.category === "siswa").length;
    const prodi = SCHEDULE_DATA.filter((i) => i.category === "prodi").length;
    animateNumber(els.statTotal, total);
    animateNumber(els.statGuru, guru);
    animateNumber(els.statSiswa, siswa);
    animateNumber(els.statProdi, prodi);
  }

  function animateNumber(el, target) {
    const start = 0;
    const dur = 600;
    const t0 = performance.now();
    function tick(t) {
      const p = Math.min(1, (t - t0) / dur);
      const eased = 1 - Math.pow(1 - p, 3);
      el.textContent = Math.round(start + (target - start) * eased);
      if (p < 1) requestAnimationFrame(tick);
    }
    requestAnimationFrame(tick);
  }

  function render() {
    updateFavCount();
    const list = getFiltered(false);
    updateSearchCounter(list.length);

    if (list.length === 0) {
      els.cardGrid.hidden = true;
      els.tableWrap.hidden = true;
      els.pagination.innerHTML = "";
      els.emptyState.hidden = false;
      return;
    }
    els.emptyState.hidden = true;

    const totalPages = Math.max(1, Math.ceil(list.length / state.perPage));
    state.page = Math.min(state.page, totalPages);
    const startIdx = (state.page - 1) * state.perPage;
    const pageItems = list.slice(startIdx, startIdx + state.perPage);

    if (state.view === "grid") {
      els.tableWrap.hidden = true;
      els.cardGrid.hidden = false;
      renderGrid(pageItems);
    } else {
      els.cardGrid.hidden = true;
      els.tableWrap.hidden = false;
      renderTable(pageItems, startIdx);
    }

    renderPagination(totalPages);
  }

  function renderFavoritesView() {
    const list = getFiltered(true);
    updateSearchCounter(list.length, true);
    els.cardGrid.hidden = false;
    els.tableWrap.hidden = true;
    els.emptyState.hidden = list.length !== 0;
    els.pagination.innerHTML = "";
    if (list.length === 0) {
      els.emptyState.querySelector("h2").textContent = "Belum ada jadwal favorit.";
      els.emptyState.querySelector("p").textContent = "Tandai dokumen dengan ikon bintang untuk menambahkannya ke sini.";
      return;
    }
    els.emptyState.querySelector("h2").textContent = "Belum ada jadwal tersedia.";
    els.emptyState.querySelector("p").textContent = "Coba ubah kata kunci pencarian atau atur ulang filter kategori.";
    renderGrid(list);
  }

  function highlight(text) {
    if (!state.query) return escapeHtml(text);
    const q = state.query;
    const idx = text.toLowerCase().indexOf(q);
    if (idx === -1) return escapeHtml(text);
    return (
      escapeHtml(text.slice(0, idx)) +
      "<mark>" + escapeHtml(text.slice(idx, idx + q.length)) + "</mark>" +
      escapeHtml(text.slice(idx + q.length))
    );
  }

  function escapeHtml(str) {
    return str.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }

  function badgeClass(category) {
    return { guru: "badge--guru", siswa: "badge--siswa", prodi: "badge--prodi" }[category] || "badge--siswa";
  }

  function formatDate(iso) {
    const d = new Date(iso + "T00:00:00");
    return d.toLocaleDateString("id-ID", { day: "2-digit", month: "short", year: "numeric" });
  }

